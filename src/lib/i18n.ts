const dict: Record<Lang, Record<string, string>> = { en, es };

export function t(lang: Lang, key: string, params?: Params): string {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      // Compass points and risk levels are translated too.
      const val = k === "dir" ? t(lang, `compass.${v}`) : k === "level" ? t(lang, `level.${v}`) : String(v);
      s = s.split(`{${k}}`).join(val);
    }
  }
  return s;
}

export function tm(lang: Lang, m: Msg) {
  return t(lang, m.key, m.params);
}

// "about 3 hours", "about 2 days", for the arrival estimate
export function hoursText(lang: Lang, h: number) {
  if (h < 1) return t(lang, "ui.h.under");
  if (h < 48) return t(lang, "ui.h.hours", { n: Math.round(h) });
  if (h < 24 * 7) return t(lang, "ui.h.days", { n: Math.round(h / 24) });
  return t(lang, "ui.h.long");
}
